# Завдання 3: приводимо телефонні номери до одного вигляду +380XXXXXXXXX.

# Підключаємо модуль регулярних виразів (пошук і заміна за шаблоном)
import re


def normalize_phone(phone_number):
    """
    Залишає в номері тільки цифри та '+' на початку
    і додає код України, якщо його немає.
    """
    # Прибираємо все, що НЕ цифра і НЕ '+'.
    # [^\d+] означає "будь-який символ, крім цифри та плюса"
    phone = re.sub(r"[^\d+]", "", phone_number)

    if phone.startswith("+"):
        # Плюс уже є — номер готовий
        return phone
    elif phone.startswith("380"):
        # Код є, бракує лише плюса
        return "+" + phone
    else:
        # Коду немає (наприклад, 0501234567) — додаємо '+38'
        return "+38" + phone


if __name__ == "__main__":
    raw_numbers = [
        "067\t123 4567",
        "(095) 234-5678\n",
        "+380 44 123 4567",
        "380501234567",
        "    +38(050)123-32-34",
        "     0503451234",
        "(050)8889900",
        "38050-111-22-22",
        "38050 111 22 11   ",
    ]

    sanitized_numbers = [normalize_phone(num) for num in raw_numbers]
    print("Нормалізовані номери телефонів для SMS-розсилки:", sanitized_numbers)
