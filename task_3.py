# Завдання 3: приводимо телефонні номери до одного вигляду +380XXXXXXXXX.

# Підключаємо модуль регулярних виразів (пошук і заміна за шаблоном)
import re


def normalize_phone(phone_number):
    """
    Залишає в номері тільки цифри та '+' на початку
    і додає код України, якщо його немає.
    """
    # Прибираємо ВСЕ, що не цифра (навіть '+').
    # \D означає "будь-який символ, крім цифри".
    # Плюс ми потім самі поставимо на початок —
    # так він ніколи не опиниться посередині номера.
    digits = re.sub(r"\D", "", phone_number)

    if digits.startswith("380"):
        # Код країни є, бракує лише плюса: 380501234567
        return "+" + digits
    elif digits.startswith("80"):
        # Старий формат через "8": 8 050 123 45 67
        return "+3" + digits
    else:
        # Коду немає: 0501234567 — додаємо '+38'
        return "+38" + digits


if __name__ == "__main__":
    raw_numbers = [
        "067\t123 4567",
        "(095) 234-5678\n",
        "+380 44 123 4567",
        "380501234567",
        "    +38(050)123-32-34",
        "     0503451234",
        "(050)8889900",
        "38050-111-22-22",
        "38050 111 22 11   ",
        "050+123+45+67",      # плюси посередині
        "8 050 123 45 67",    # старий формат через "8"
    ]

    sanitized_numbers = [normalize_phone(num) for num in raw_numbers]
    print("Нормалізовані номери телефонів для SMS-розсилки:", sanitized_numbers)
