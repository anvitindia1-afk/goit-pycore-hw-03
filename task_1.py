# Завдання 1: скільки днів між заданою датою і сьогоднішнім днем.

# Підключаємо модуль для роботи з датами
from datetime import datetime


def get_days_from_today(date):
    """
    Повертає кількість днів від дати date до сьогодні.
    date — рядок у форматі 'РРРР-ММ-ДД', наприклад '2020-10-09'.
    Якщо дата в майбутньому, число буде від'ємним.
    Якщо формат неправильний, повертає None.
    """
    try:
        # Перетворюємо рядок на дату. .date() відкидає години й хвилини
        given_date = datetime.strptime(date, "%Y-%m-%d").date()
    except (ValueError, TypeError):
        # Сюди потрапимо, якщо рядок не схожий на дату
        print(f"Неправильний формат дати: {date}. Потрібно 'РРРР-ММ-ДД'.")
        return None

    # Беремо сьогоднішню дату (теж без часу)
    today = datetime.today().date()

    # Віднімаємо дати й беремо з різниці лише кількість днів
    difference = today - given_date
    return difference.days


# Цей блок працює лише тоді, коли ми запускаємо саме цей файл
if __name__ == "__main__":
    print(get_days_from_today("2021-10-09"))
    print(get_days_from_today("2030-01-01"))  # майбутнє — буде від'ємне число
    print(get_days_from_today("09.10.2021"))  # неправильний формат
